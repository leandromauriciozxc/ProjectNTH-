using System;
using System.Collections.Generic;
using System.Security.Cryptography;
using System.Text;
using System.Text.RegularExpressions;

namespace ProjectNTH.Dialogue.Authoring
{
    /// <summary>One deterministic, plain-text Yarn node per conversation. No handwritten commands.</summary>
    public static class DialogueYarnText
    {
        public const string Command = "nth_authored_step";
        public const string StopVariable = "$nth_authored_stop";
        private static readonly Regex IdPattern = new Regex("^[a-f0-9]{32}$");
        private static readonly Regex NamePattern = new Regex(@"^[\p{L}\p{N} _.'-]+$");

        public static List<string> Validate(DialogueConversation conversation)
        {
            var errors = new List<string>();
            if (conversation == null) { errors.Add("Choose a Conversation asset."); return errors; }
            if (!IdPattern.IsMatch(conversation.AssetId ?? "")) errors.Add("Save this conversation as an asset, then generate its Yarn file.");
            if (conversation.steps.Count == 0) errors.Add("Add at least one dialogue step.");
            var ids = new HashSet<string>();
            for (int i = 0; i < conversation.steps.Count; i++)
            {
                var step = conversation.steps[i];
                string prefix = "Step " + (i + 1) + ": ";
                if (step == null) { errors.Add(prefix + "Missing entry."); continue; }
                if (!IdPattern.IsMatch(step.id ?? "") || !ids.Add(step.id)) errors.Add(prefix + "Invalid or duplicate step ID. Recreate this entry.");
                if (!Enum.IsDefined(typeof(DialogueStepKind), step.kind)) errors.Add(prefix + "Unknown step type.");
                if (step.kind == DialogueStepKind.Line)
                {
                    if (step.character == null) errors.Add(prefix + "Choose a character.");
                    else if (string.IsNullOrWhiteSpace(step.character.displayName) || !NamePattern.IsMatch(step.character.displayName))
                        errors.Add(prefix + "Character names can contain letters, numbers, spaces, apostrophes, dots, underscores and hyphens.");
                    if (string.IsNullOrWhiteSpace(step.text)) errors.Add(prefix + "Write the dialogue text.");
                    ValidateClip(step.voice, step.character, DialogueAudioKind.Voice, prefix, errors);
                }
                if (step.kind == DialogueStepKind.Line || step.kind == DialogueStepKind.SoundEffect)
                {
                    ValidateClip(step.soundEffect, step.character, DialogueAudioKind.SoundEffect, prefix, errors);
                    if (step.kind == DialogueStepKind.SoundEffect && (step.soundEffect == null || step.soundEffect.mode == DialogueClipMode.None))
                        errors.Add(prefix + "Choose a sound effect.");
                }
                if (step.kind == DialogueStepKind.SceneAction && string.IsNullOrWhiteSpace(step.actionLabel)) errors.Add(prefix + "Give the action a label.");
                if (step.kind == DialogueStepKind.Wait && (float.IsNaN(step.waitSeconds) || float.IsInfinity(step.waitSeconds) || step.waitSeconds < 0))
                    errors.Add(prefix + "Wait time must be a non-negative number.");
            }
            return errors;
        }

        private static void ValidateClip(DialogueClipSelection selection, DialogueCharacter character, DialogueAudioKind kind, string prefix, List<string> errors)
        {
            if (selection == null) { errors.Add(prefix + "Missing audio selection."); return; }
            if (selection.mode == DialogueClipMode.None) return;
            if (!Enum.IsDefined(typeof(DialogueClipMode), selection.mode) || selection.Resolve(character, kind, out _) == null)
                errors.Add(prefix + kind + " has a missing clip or character-library entry. Choose an available sound or None.");
        }

        public static string Generate(DialogueConversation conversation)
        {
            var text = new StringBuilder();
            text.Append("// Generated by Project NTH Dialogue Authoring. Edit the Conversation asset.\n");
            text.Append("// Source asset: ").Append(conversation.AssetId).Append('\n');
            text.Append("title: ").Append(conversation.NodeName).Append("\n---\n");
            text.Append("<<set ").Append(StopVariable).Append(" = false>>\n");
            foreach (var step in conversation.steps)
            {
                text.Append("<<").Append(Command).Append(' ').Append(step.id).Append(">>\n");
                // Stop in Yarn itself after a command drains, before it can advance to another line/action.
                text.Append("<<if ").Append(StopVariable).Append(">>\n    <<stop>>\n<<endif>>\n");
                if (step.kind != DialogueStepKind.Line) continue;
                text.Append(step.character.displayName.Trim()).Append(": ").Append(Escape(step.text));
                text.Append(" #line:authored_").Append(conversation.AssetId).Append('_').Append(step.id).Append('\n');
            }
            return text.Append("===\n").ToString();
        }

        public static string Fingerprint(DialogueConversation conversation)
        {
            using (var sha = SHA256.Create())
                return BitConverter.ToString(sha.ComputeHash(Encoding.UTF8.GetBytes(Generate(conversation)))).Replace("-", "").ToLowerInvariant();
        }

        public static string Escape(string value)
        {
            var text = new StringBuilder();
            foreach (char c in (value ?? "").Trim())
            {
                // A multi-line Inspector entry remains one Yarn line. Yarn syntax is treated literally.
                if (c == '\r') continue;
                if (c == '\n' || c == '\t') { text.Append(' '); continue; }
                if ("\\{}#<>/[]".IndexOf(c) >= 0) text.Append('\\');
                text.Append(c);
            }
            return text.ToString();
        }
    }
}
